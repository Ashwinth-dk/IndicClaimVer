def populate_dataset():
    print("Populating verified multilingual dataset across EN, TA, HI, MR...")
    dm = DatasetManager()
    em = EvidenceManager()

    existing_items = dm.load_all()
    existing_claims = {it.get("Text", "").strip().lower() for it in existing_items}

    added_count = 0
    new_evidence = []
    
    for item in VERIFIED_MULTILINGUAL_DATA:
        claim_text = item["Text"].strip()
        evidence_text = item["Evidence"].strip()
        label = item["Label"]
        lang = item["Language"]

        if claim_text.lower() not in existing_claims:
            dm.add_item(
                text=claim_text,
                evidence=evidence_text,
                label=label,
                language=lang,
                source="Verified Fact Repository"
            )
            existing_claims.add(claim_text.lower())
            added_count += 1
            new_evidence.append(evidence_text)

    if new_evidence:
        em.add_evidence_batch(new_evidence)

    stats = dm.get_stats()
    print(f"\nIngestion Complete! Added {added_count} new multilingual items.")
    print("Current Dataset Statistics:")
    print(f"  Total items:    {stats['total_count']}")
    print(f"  SUPPORTS:       {stats['supports_count']}")
    print(f"  REFUTES:        {stats['refutes_count']}")
    print(f"  Balance ratio:  {stats['balance_ratio']}")
    print(f"  Languages:      {stats.get('languages', {})}")

if __name__ == "__main__":
    populate_dataset()
